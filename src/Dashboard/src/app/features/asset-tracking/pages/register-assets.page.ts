import { ChangeDetectionStrategy, Component, inject, signal } from '@angular/core';
import { FormArray, FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { MatAutocompleteModule, MatAutocompleteSelectedEvent } from '@angular/material/autocomplete';
import { MatButtonModule } from '@angular/material/button';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatIconModule } from '@angular/material/icon';
import { MatInputModule } from '@angular/material/input';
import { MatSelectModule } from '@angular/material/select';
import { Router } from '@angular/router';
import {
  ASSET_CLASSIFICATIONS,
  ASSET_CONDITIONS,
  REGISTRATION_STATUSES,
  SiteLookup,
  UserLookup
} from '../models/asset-tracking.models';
import { AssetTrackingService } from '../services/asset-tracking.service';

@Component({
  selector: 'app-register-assets-page',
  imports: [
    ReactiveFormsModule,
    MatAutocompleteModule,
    MatButtonModule,
    MatFormFieldModule,
    MatIconModule,
    MatInputModule,
    MatSelectModule
  ],
  template: `
    <main class="tracking-page">
      <header>
        <div>
          <h2>Register Assets</h2>
          <p>
            Register up to 50 individual machines or tools atomically. Codes and QR
            identifiers are generated by the aggregate.
          </p>
        </div>
      </header>
      <form class="card form-grid" [formGroup]="form" (ngSubmit)="submit()">
        <mat-form-field>
          <mat-label>Classification</mat-label>
          <mat-select formControlName="classification">
            @for (value of classifications; track value) {
              <mat-option [value]="value">{{ value }}</mat-option>
            }
          </mat-select>
        </mat-form-field>
        <mat-form-field>
          <mat-label>Name</mat-label>
          <input matInput formControlName="name" />
        </mat-form-field>
        <mat-form-field>
          <mat-label>Manufacturer (optional)</mat-label>
          <input matInput formControlName="manufacturer" />
        </mat-form-field>
        <mat-form-field>
          <mat-label>Model (optional)</mat-label>
          <input matInput formControlName="model" />
        </mat-form-field>
        <mat-form-field class="wide">
          <mat-label>Description (optional)</mat-label>
          <textarea matInput formControlName="description"></textarea>
        </mat-form-field>
        <mat-form-field>
          <mat-label>Site</mat-label>
          <input
            matInput
            formControlName="siteSearch"
            [matAutocomplete]="siteAuto"
            (input)="searchSites($event)"
          />
          <mat-autocomplete
            #siteAuto="matAutocomplete"
            (optionSelected)="selectSite($event)"
          >
            @for (item of sites(); track item.id) {
              <mat-option [value]="item.id">{{ item.name }} · {{ item.address }}</mat-option>
            }
          </mat-autocomplete>
        </mat-form-field>
        <mat-form-field>
          <mat-label>Responsible worker (optional)</mat-label>
          <input
            matInput
            formControlName="workerSearch"
            [matAutocomplete]="workerAuto"
            (input)="searchWorkers($event)"
          />
          <mat-autocomplete
            #workerAuto="matAutocomplete"
            (optionSelected)="selectWorker($event)"
          >
            @for (item of workers(); track item.id) {
              <mat-option [value]="item.id">{{ item.displayName }}</mat-option>
            }
          </mat-autocomplete>
        </mat-form-field>
        <mat-form-field>
          <mat-label>Condition</mat-label>
          <mat-select formControlName="condition">
            @for (value of conditions; track value) {
              <mat-option [value]="value">{{ value }}</mat-option>
            }
          </mat-select>
        </mat-form-field>
        <mat-form-field>
          <mat-label>Operational status</mat-label>
          <mat-select formControlName="operationalStatus">
            @for (value of statuses; track value) {
              <mat-option [value]="value">{{ value }}</mat-option>
            }
          </mat-select>
        </mat-form-field>
        <mat-form-field class="wide">
          <mat-label>Shared note</mat-label>
          <textarea matInput formControlName="note"></textarea>
        </mat-form-field>
        <section class="wide" formArrayName="rows">
          <h3>Registration rows</h3>
          @for (row of rows.controls; track row; let index = $index) {
            <div [formGroupName]="index" class="actions">
              <mat-form-field>
                <mat-label>Serial number {{ index + 1 }} (optional)</mat-label>
                <input matInput formControlName="manufacturerSerialNumber" />
              </mat-form-field>
              <button
                mat-icon-button
                type="button"
                aria-label="Remove registration row"
                [disabled]="rows.length === 1"
                (click)="removeRow(index)"
              >
                <mat-icon>delete</mat-icon>
              </button>
            </div>
          }
        </section>
        <div class="wide actions">
          <button
            mat-stroked-button
            type="button"
            (click)="addRow()"
            [disabled]="rows.length >= 50"
          >
            Add row
          </button>
          <button mat-flat-button type="submit" [disabled]="form.invalid || saving()">
            Register {{ rows.length }} asset{{ rows.length === 1 ? '' : 's' }}
          </button>
        </div>
        @if (message()) {
          <p class="wide" [class.error]="failed()" role="status">{{ message() }}</p>
        }
      </form>
    </main>
  `,
  styleUrl: '../asset-tracking.css',
  changeDetection: ChangeDetectionStrategy.OnPush
})
export class RegisterAssetsPage {
  private readonly service = inject(AssetTrackingService);
  private readonly router = inject(Router);

  readonly sites = signal<readonly SiteLookup[]>([]);
  readonly workers = signal<readonly UserLookup[]>([]);
  readonly saving = signal(false);
  readonly failed = signal(false);
  readonly message = signal('');
  readonly classifications = ASSET_CLASSIFICATIONS;
  readonly conditions = ASSET_CONDITIONS;
  readonly statuses = REGISTRATION_STATUSES;

  readonly form = new FormGroup({
    classification: new FormControl<'Machine' | 'Tool'>('Machine', {
      nonNullable: true,
      validators: Validators.required
    }),
    name: new FormControl('', {
      nonNullable: true,
      validators: [Validators.required, Validators.maxLength(200)]
    }),
    manufacturer: new FormControl('', {
      nonNullable: true,
      validators: Validators.maxLength(100)
    }),
    model: new FormControl('', {
      nonNullable: true,
      validators: Validators.maxLength(100)
    }),
    description: new FormControl('', {
      nonNullable: true,
      validators: Validators.maxLength(2000)
    }),
    siteId: new FormControl('', { nonNullable: true, validators: Validators.required }),
    siteSearch: new FormControl('', { nonNullable: true, validators: Validators.required }),
    responsibleWorkerId: new FormControl<string | null>(null),
    workerSearch: new FormControl('', { nonNullable: true }),
    condition: new FormControl<'Good' | 'Damaged' | 'Unsafe'>('Good', {
      nonNullable: true,
      validators: Validators.required
    }),
    operationalStatus: new FormControl<'Available' | 'InUse' | 'UnderRepair'>('Available', {
      nonNullable: true,
      validators: Validators.required
    }),
    note: new FormControl('', { nonNullable: true, validators: Validators.maxLength(2000) }),
    rows: new FormArray([this.newRow()])
  });

  get rows() {
    return this.form.controls.rows;
  }

  newRow() {
    return new FormGroup({
      manufacturerSerialNumber: new FormControl('', {
        nonNullable: true,
        validators: Validators.maxLength(100)
      })
    });
  }

  addRow(): void {
    if (this.rows.length < 50) {
      this.rows.push(this.newRow());
    }
  }

  removeRow(index: number): void {
    if (this.rows.length > 1) {
      this.rows.removeAt(index);
    }
  }

  async searchSites(event: Event): Promise<void> {
    this.form.controls.siteId.setValue('');
    this.sites.set(await this.service.searchSites((event.target as HTMLInputElement).value));
  }

  async searchWorkers(event: Event): Promise<void> {
    this.form.controls.responsibleWorkerId.setValue(null);
    this.workers.set(await this.service.searchWorkers((event.target as HTMLInputElement).value));
  }

  selectSite(event: MatAutocompleteSelectedEvent): void {
    const item = this.sites().find((site) => site.id === event.option.value);
    this.form.patchValue({ siteId: event.option.value, siteSearch: item?.name ?? '' });
  }

  selectWorker(event: MatAutocompleteSelectedEvent): void {
    const item = this.workers().find((worker) => worker.id === event.option.value);
    this.form.patchValue({
      responsibleWorkerId: event.option.value,
      workerSearch: item?.displayName ?? ''
    });
  }

  async submit(): Promise<void> {
    if (this.form.invalid) {
      this.form.markAllAsTouched();
      return;
    }

    this.saving.set(true);
    this.message.set('');
    this.failed.set(false);
    try {
      const value = this.form.getRawValue();
      const result = await this.service.register({
        classification: value.classification,
        name: value.name,
        manufacturer: value.manufacturer || null,
        model: value.model || null,
        description: value.description || null,
        siteId: value.siteId,
        responsibleWorkerId: value.responsibleWorkerId,
        condition: value.condition,
        operationalStatus: value.operationalStatus,
        note: value.note || null,
        rows: value.rows.map((row) => ({
          manufacturerSerialNumber: row.manufacturerSerialNumber || null
        }))
      });
      await this.service.invalidate();
      this.message.set(`${result.length} asset${result.length === 1 ? '' : 's'} registered.`);
      if (result.length === 1) {
        await this.router.navigate(['/asset-tracking/assets', result[0].id]);
      }
    } catch {
      this.failed.set(true);
      this.message.set(
        'Registration failed. No rows were registered. Review the asset, Site, Worker and values.'
      );
    } finally {
      this.saving.set(false);
    }
  }
}
